import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';
import {staffCan,mfaQrSource,STAFF_AUTH_OPTIONS} from '../src/staff-access.js';

test('staff clients do not remember logins and expose only appropriate role actions',()=>{
 assert.equal(STAFF_AUTH_OPTIONS.persistSession,false);
 assert.equal(STAFF_AUTH_OPTIONS.autoRefreshToken,false);
 assert.equal(STAFF_AUTH_OPTIONS.detectSessionInUrl,false);
 assert.equal(staffCan('editor','draft','products'),true);
 assert.equal(staffCan('editor','publish','products'),false);
 assert.equal(staffCan('editor','tab','orders'),false);
 assert.equal(staffCan('manager','publish','products'),true);
 assert.equal(staffCan('manager','payouts'),false);
 assert.equal(staffCan('super_admin','payouts'),true);
 assert.equal(staffCan('customer','tab','overview'),false);
 const svg='<svg xmlns="http://www.w3.org/2000/svg"><path d="M0 0"/></svg>';
 assert.equal(mfaQrSource('data:image/svg+xml;utf-8,'+svg),mfaQrSource(svg));
 assert.ok(mfaQrSource(svg).startsWith('data:image/svg+xml;charset=utf-8,%3Csvg'));
 assert.equal(mfaQrSource('<script>bad</script>'),'');
 // Supabase Auth generates this XML preamble before the SVG root.
 const supabaseSvg='<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n'+svg;
 const qr=mfaQrSource('data:image/svg+xml;utf-8,'+supabaseSvg);
 assert.ok(qr);
 assert.equal(decodeURIComponent(qr.split(',')[1]),supabaseSvg);
 assert.equal(mfaQrSource(supabaseSvg),qr);
 assert.equal(mfaQrSource('<?xml version="1.0"?><script>bad</script>'),'');
});

test('staff RLS requires password + MFA and enforces roles, expiry and immediate revocation',async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon;create role authenticated;create role service_role bypassrls;create schema auth;create table auth.users(id uuid primary key);create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;create function auth.jwt() returns jsonb language sql stable as $$ select coalesce(nullif(current_setting('request.jwt.claims',true),''),'{}')::jsonb $$;grant usage on schema auth to anon,authenticated,service_role;create schema storage;create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text);alter table storage.objects enable row level security;grant usage on schema storage to authenticated;grant select,insert on storage.objects to authenticated;`);
  for(const f of ['01-schema.sql','04-maker-stories.sql','05-admin.sql','06-staff-roles.sql','06-staff-roles.sql'])await db.exec(await readFile(new URL('../supabase/sql/'+f,import.meta.url),'utf8'));
  const oldBootstrap=await readFile(new URL('../supabase/sql/05-admin.sql',import.meta.url),'utf8');
  await assert.rejects(()=>db.exec(oldBootstrap),/Staff roles are already installed/);
  await db.exec('rollback');
  const ids=Array.from({length:5},()=>crypto.randomUUID());
  const [director,manager,editor,customer,maker]=ids;
  for(const id of ids.slice(0,4))await db.query('insert into auth.users values($1)',[id]);
  for(const [id,role] of [[director,'super_admin'],[manager,'manager'],[editor,'editor']])await db.query('insert into public.admin_users(user_id,role) values($1,$2)',[id,role]);
  await db.query(`insert into public.makers(id,name,craft,story,image,published) values($1,'Draft maker','Clay','Life story','/image.jpg',false)`,[maker]);
  await db.query(`insert into public.maker_payment_accounts values($1,'acc_test',true)`,[maker]);
  await db.query(`insert into public.orders(user_id,idempotency_key,status,total_paise,shipping) values($1,gen_random_uuid(),'paid',10000,'{}')`,[customer]);
  await db.exec(`insert into public.enquiries(name,email,topic,message) values('Visitor','visitor@example.com','General enquiry','Private enquiry content')`);
  const login=async(id,{aal='aal2',method='password',age=0}={})=>{
   await db.exec('reset role;set role authenticated');
   await db.query(`select set_config('request.jwt.claim.sub',$1,false),set_config('request.jwt.claims',$2,false)`,[id,JSON.stringify({aal,amr:[{method,timestamp:Math.floor(Date.now()/1000)-age}]})]);
  };
  await login(editor);
  assert.equal((await db.query('select * from public.makers')).rows.length,1);
  await db.exec(`update public.makers set story='Draft edited'`);
  await assert.rejects(()=>db.exec(`update public.makers set published=true`),/row-level security/);
  assert.equal((await db.query('select * from public.enquiries')).rows.length,0);
  assert.equal((await db.query('select * from public.orders')).rows.length,0);
  assert.equal((await db.query('select * from public.maker_payment_accounts')).rows.length,0);
  await assert.rejects(()=>db.exec(`insert into public.site_content(key,value) values('foundation','{}')`),/row-level security/);
  await db.exec(`insert into storage.objects(bucket_id) values('kcg-media')`);
  await login(manager);
  await db.exec(`update public.makers set published=true;insert into public.site_content(key,value) values('foundation','{}')`);
  assert.equal((await db.query('select * from public.enquiries')).rows.length,1);
  assert.equal((await db.query('select * from public.orders')).rows.length,1);
  assert.equal((await db.query('select * from public.maker_payment_accounts')).rows.length,0);
  await db.exec(`update public.orders set status='shipped'`);
  await assert.rejects(()=>db.exec(`update public.orders set total_paise=1`),/permission denied/);
  await login(editor);
  assert.equal((await db.query(`update public.makers set story='Tampered published text' returning id`)).rows.length,0);
  await login(director);
  assert.equal((await db.query('select * from public.maker_payment_accounts')).rows.length,1);
  await assert.rejects(()=>db.query(`insert into public.admin_users(user_id,role) values($1,'super_admin')`,[customer]),/permission denied/);
  for(const claims of [{aal:'aal1'},{method:'otp'},{age:1900}]){
   await login(director,claims);
   assert.equal((await db.query('select * from public.enquiries')).rows.length,0);
   await assert.rejects(()=>db.exec(`insert into storage.objects(bucket_id) values('kcg-media')`),/row-level security/);
  }
  await login(director);
  await db.exec('reset role');await db.query('update public.admin_users set enabled=false where user_id=$1',[director]);
  await login(director);
  assert.equal((await db.query('select * from public.enquiries')).rows.length,0,'revoked membership must override an unchanged valid JWT');
  await login(customer);
  assert.equal((await db.query(`select public.staff_has_role(array['super_admin','manager','editor']) as allowed`)).rows[0].allowed,false);
  assert.equal((await db.query('select * from public.admin_users')).rows.length,0);
  await db.exec('reset role;set role anon');
  assert.equal((await db.query('select * from public.makers')).rows.length,1,'public published stories remain readable without staff privileges');
 }finally{await db.close();}
});
